import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import test from "node:test";
import { captureHostLog, type HostLogEntry } from "@molis-ai/molis-work-app-local-host";
import { MemoryService } from "@molis-ai/molis-work-service-memory";
import { openGoalBrowser } from "./fixtures/goal-browser.js";
import { issueModel } from "./fixtures/issue-model.js";
import { openWork, putInput, readWork, waitWork } from "./fixtures/assistant-send-journey.js";
import { CURRENT_WORK, OPEN_DETAILS } from "./fixtures/assistant-current-work.js";
import { reviewEvidenceUrl, shouldSaveReviewScreenshots } from "./fixtures/review-evidence.js";

test("QEA-50 · unreadable memory suggestions keep the conversation and draft, retry restores real candidates or an empty result", { timeout: 120_000 }, async t => {
  const logs: HostLogEntry[] = [];
  t.after(captureHostLog(logs));
  let unavailable = false;
  const candidates = MemoryService.prototype.candidates;
  const reading = new Set<ReturnType<typeof candidates>>();
  t.mock.method(MemoryService.prototype, "candidates", function (this: MemoryService, ...args: Parameters<typeof candidates>) {
    if (unavailable) return Promise.reject(new Error("fixture-private-memory-read-detail"));
    const result = candidates.apply(this, args).finally(() => reading.delete(result));
    reading.add(result); return result;
  });
  const failReads = async () => { unavailable = true; await Promise.allSettled([...reading]); };
  const browser = await openGoalBrowser(t, "user", undefined, undefined, undefined, undefined, {
    prepareHome: async homeDirectory => { await issueModel(t, homeDirectory, { remember: { text: "周报先写风险", said: "周报先写风险" } }); },
  });
  if (!browser) return;
  await browser.command("Emulation.setDeviceMetricsOverride", { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false }, browser.sessionId);
  await browser.command("Emulation.setEmulatedMedia", { features: [{ name: "prefers-reduced-motion", value: "reduce" }] }, browser.sessionId);
  await browser.navigate(() => browser.command("Page.navigate", { url: browser.origin + "/" }, browser.sessionId));
  await browser.waitFor(`document.querySelector('.chooser')?.dataset.selected === ${JSON.stringify(browser.projectId)}`);
  const prompt = "帮我整理这周的周报。另外请记住：周报先写风险";
  await putInput(browser, prompt);
  await browser.click("[data-assistant-composer] [data-composer-send]");
  await browser.waitFor("document.querySelector('[data-assistant-composer] .mw-composer__input').value === ''", 15_000);
  const id = await browser.evaluate<string>(CURRENT_WORK);
  const initial = await waitWork(browser, id, view => view.work.state === "completed" && view.memory_candidates?.length === 1);
  const candidate = initial.memory_candidates![0]!;
  const draft = "补充尚未发送，请保留";
  await putInput(browser, draft);
  await failReads();
  const failed = await readWork(browser, id);
  assert.equal(failed.work.state, "completed");
  assert.equal(failed.memory_candidates, null, "a failed owner read is distinct from an empty list");
  assert.deepEqual(failed.rounds.map(round => [round.run_id, round.text, round.phase]), initial.rounds.map(round => [round.run_id, round.text, round.phase]), "a memory read failure does not replace the conversation");
  const direct = await browser.evaluate<{ status: number; body: { error: string; code: string } }>("fetch('/api/assistant/memory-candidates').then(async response => ({ status: response.status, body: await response.json() }))");
  assert.equal(direct.status, 500, "the independent list cannot claim a successful empty read");
  assert.equal(direct.body.code, "actions.execution_failed");
  assert.equal(direct.body.error, "记忆建议暂时读不到");
  assert.doesNotMatch(JSON.stringify(direct.body), /fixture-private-memory-read-detail/);
  await browser.navigate(() => browser.command("Page.reload", { ignoreCache: true }, browser.sessionId));
  await openWork(browser, id);
  const attention = "[data-assistant-block='attention']";
  await browser.waitFor(`document.querySelector(${JSON.stringify(attention)})?.textContent.includes('记忆建议暂时读不到')`);
  assert.equal(await browser.evaluate("document.querySelector('[data-assistant-composer] .mw-composer__input').value"), draft);
  assert.doesNotMatch(await browser.evaluate<string>("document.body.textContent"), /fixture-private-memory-read-detail/);
  assert.equal(await browser.evaluate(`document.querySelector(${JSON.stringify(attention)}).querySelectorAll('.assistant-item-actions button').length`), 1, "only retry is offered while candidate facts are unavailable");
  assert.equal(await browser.evaluate("document.querySelector('[data-assistant-side-dot]').hidden"), false);
  const diagnostic = logs.filter(entry => entry.event === "memory_candidates_unavailable" && entry.fields?.work_id === id);
  assert.ok(diagnostic.length >= 1, "the failed read has a diagnostic for its actual work");
  assert.equal(diagnostic[0]?.error?.name, "Error");
  assert.doesNotMatch(JSON.stringify(logs), /fixture-private-memory-read-detail/);
  const saveShots = shouldSaveReviewScreenshots();
  const evidence = reviewEvidenceUrl("quality-audit-memory/"); if (saveShots) await mkdir(evidence, { recursive: true });
  for (const width of [1440, 1024, 390]) for (const theme of ["light", "dark"]) {
    await browser.command("Emulation.setDeviceMetricsOverride", { width, height: 900, deviceScaleFactor: 1, mobile: false }, browser.sessionId);
    await browser.command("Emulation.setEmulatedMedia", { features: [{ name: "prefers-color-scheme", value: theme }, { name: "prefers-reduced-motion", value: "reduce" }] }, browser.sessionId);
    // The work's details (its path, sub-tasks, results and changes) are behind 更多 › 详情 (36A-3).
    await browser.evaluate(OPEN_DETAILS);
    await browser.waitFor(`document.querySelector(${JSON.stringify(attention)}).getBoundingClientRect().width > 0`);
    if (saveShots) await writeFile(new URL(`candidate-unavailable-${theme}-${width}.png`, evidence), Buffer.from((await browser.command<{ data: string }>("Page.captureScreenshot", { format: "png" }, browser.sessionId)).data, "base64"));
  }
  await browser.click(`${attention} .assistant-item-actions button`);
  await browser.waitFor(`!document.querySelector(${JSON.stringify(attention)}).querySelector('.assistant-item-actions button').disabled`);
  assert.equal((await readWork(browser, id)).memory_candidates, null, "a retry while storage is still unavailable retains the explicit failure");
  assert.equal(logs.filter(entry => entry.event === "memory_candidates_unavailable" && entry.fields?.work_id === id).length, diagnostic.length, "stable failing reads do not flood the log");
  unavailable = false;
  await browser.click(`${attention} .assistant-item-actions button`);
  await browser.waitFor(`document.querySelector(${JSON.stringify(attention)})?.textContent.includes('你刚才让我记住：周报先写风险')`);
  assert.equal((await readWork(browser, id)).memory_candidates?.[0]?.candidate_id, candidate.candidate_id);
  await browser.click(`${attention} .assistant-item-actions button`);
  await waitWork(browser, id, view => view.memory_candidates === undefined);
  const stored = await browser.evaluate<{ items: { text: string; version: number }[]; changes: { text: string; kind: string }[] }>("fetch('/api/memory/overview?scope=personal').then(response => response.json())");
  assert.deepEqual(stored.items.filter(item => item.text === candidate.text).map(item => item.version), [1], "the real owner has exactly one first version after the normal Keep action");
  assert.equal(stored.changes.filter(change => change.text === candidate.text && change.kind === "accepted").length, 1, "the decision creates one business ledger change");
  await failReads();
  await browser.navigate(() => browser.command("Page.reload", { ignoreCache: true }, browser.sessionId));
  await openWork(browser, id);
  await browser.waitFor(`document.querySelector(${JSON.stringify(attention)})?.textContent.includes('记忆建议暂时读不到')`);
  const newFailures = logs.filter(entry => entry.event === "memory_candidates_unavailable" && entry.fields?.work_id === id).length;
  assert.ok(newFailures > diagnostic.length, "a successful owner read ends the previous diagnostic episode");
  await readWork(browser, id); await readWork(browser, id);
  assert.equal(logs.filter(entry => entry.event === "memory_candidates_unavailable" && entry.fields?.work_id === id).length, newFailures, "new stable failure is reported once regardless of earlier interleaving");
  // The work's details (its path, sub-tasks, results and changes) are behind 更多 › 详情 (36A-3).
  await browser.evaluate(OPEN_DETAILS);
  unavailable = false;
  await browser.click(`${attention} .assistant-item-actions button`);
  await browser.waitFor(`!document.querySelector(${JSON.stringify(attention)})?.textContent.includes('记忆建议暂时读不到')`);
  assert.equal((await readWork(browser, id)).memory_candidates, undefined);
  assert.equal(await browser.evaluate("document.querySelector('[data-assistant-composer] .mw-composer__input').value"), draft);
});
