import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import type { PluginRegistration } from "@molis-ai/molis-work-contracts/platform/plugin-registration";
import { BUILTIN_PLUGIN_CATALOG } from "@molis-ai/molis-work-app-workbench";
import { catalogProblems } from "@molis-ai/molis-work-app-local-host";
import { CATALOG_FILE, PLATFORM_FILE, pluginRegistry, pluginRegistryProblems } from "../scripts/generate-plugin-registry.mjs";
import { WORKSPACE_PACKAGES } from "../scripts/workspace-packages.mjs";

// W5-02 (specs/repository-anti-corruption/privileges.md PG-065): each built-in plugin writes its catalog entry in its own
// src/registration.ts, and scripts/generate-plugin-registry.mjs writes apps/workbench/src/builtin-plugins.ts (the shell's
// resources) and apps/local-host/src/plugin-registry.generated.ts (the platform's list, W5-02 PR-B) from them. These tests drive
// the generator's pure functions on the repository's own tree with one file changed at a time, and the built catalog's validator
// on mutated copies. Isolated child processes also load the real public Host entry with bad catalogs supplied at the module
// loader boundary, proving that module initialization itself refuses them.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tracked = execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8" }).split("\n").filter(Boolean);
const FEED = "plugins/native/feed/src/registration.ts", FEED_PACKAGE = "plugins/native/feed/package.json";
const readReal = (file: string): string | null => { try { return readFileSync(path.join(root, file), "utf8"); } catch { return null; } };

type Entry = { path: string; name: string };
/** The repository as it is, with some files replaced (a string) or removed (null). */
function tree(changes: Record<string, string | null> = {}) {
  const files = [...new Set([...tracked, ...Object.keys(changes)])].filter(file => changes[file] !== null);
  return { files, read: (file: string) => (file in changes ? changes[file] : readReal(file)) ?? null };
}
const feed = (from: string, to: string) => {
  const text = readReal(FEED)!;
  assert.ok(text.includes(from), `${FEED} still has ${from}`);
  return { [FEED]: text.replace(from, to) };
};
type PackageJson = { "molis-work": Record<string, unknown>; exports: Record<string, unknown> };
const feedPackage = (edit: (json: PackageJson) => void) => {
  const json = JSON.parse(readReal(FEED_PACKAGE)!) as PackageJson;
  edit(json);
  return { [FEED_PACKAGE]: `${JSON.stringify(json, null, 2)}\n` };
};
/** The next free catalog position: they are positive integers, so a new plugin's is one past the highest. */
const NEXT_POSITION = Math.max(...BUILTIN_PLUGIN_CATALOG.map(entry => entry.catalog_order)) + 1;
const problems = (changes: Record<string, string | null>, packages: readonly Entry[] = WORKSPACE_PACKAGES) =>
  pluginRegistryProblems(tree(changes), packages).join("\n");

test("W5-02-REG-02: the repository's catalog is exactly the plugins' registrations, and --check says so", () => {
  assert.deepEqual(pluginRegistryProblems(tree(), WORKSPACE_PACKAGES), []);
  const run = spawnSync(process.execPath, ["scripts/generate-plugin-registry.mjs", "--check"], { cwd: root, encoding: "utf8" });
  assert.equal(run.status, 0, run.stderr);
  for (const file of [CATALOG_FILE, PLATFORM_FILE]) {
    const text = readReal(file)!;
    assert.match(text, /^\/\/ Generated by `node scripts\/generate-plugin-registry\.mjs`/, file);
    assert.equal(text.match(/^import \{ registration as \w+Registration \} from "[^"]+\/registration";$/gm)?.length, BUILTIN_PLUGIN_CATALOG.length, file);
  }
  const lines = (file: string) => readReal(file)!.split("\n").filter(line => line.startsWith("import {") || line.startsWith("  "));
  assert.deepEqual(lines(PLATFORM_FILE), lines(CATALOG_FILE), "RAC-567 the platform's list is the shell's, entry for entry");
});

test("W5-02-REG-02: --check fails on a catalog that is stale or edited by hand", () => {
  const catalog = readReal(CATALOG_FILE)!;
  const stale = /out of date or edited by hand; run node scripts\/generate-plugin-registry\.mjs/;
  assert.match(problems({ [CATALOG_FILE]: catalog.replace("  feedRegistration,\n", "") }), stale);
  assert.match(problems({ [CATALOG_FILE]: `${catalog}// a note\n` }), stale);
  assert.match(problems(feed("catalog_order: 10", "catalog_order: 999")), stale, "a moved entry reorders the generated list");
  assert.match(problems({ [CATALOG_FILE]: null }), stale, "a deleted catalog is not taken for a tree with nothing to list");
  // RAC-567: the platform's file is held to the same, on its own; either one stale, edited or missing fails.
  const platform = readReal(PLATFORM_FILE)!;
  const named = (changes: Record<string, string | null>) => problems(changes).split("\n").map(line => line.match(/registry: (\S+) is out of date/)?.[1]);
  assert.deepEqual(named({ [PLATFORM_FILE]: platform.replace("  feedRegistration,\n", "") }), [PLATFORM_FILE]);
  assert.deepEqual(named({ [PLATFORM_FILE]: `${platform}// a note\n` }), [PLATFORM_FILE]);
  assert.deepEqual(named({ [PLATFORM_FILE]: null }), [PLATFORM_FILE], "a missing platform list is not taken for one with nothing to list");
  assert.deepEqual(named({ [PLATFORM_FILE]: catalog }), [PLATFORM_FILE], "the shell's file under the platform's name is not the platform's list");
  assert.deepEqual(named(feed("catalog_order: 10", "catalog_order: 999")), [CATALOG_FILE, PLATFORM_FILE], "a moved entry makes both stale");
});

test("W5-02-REG-02: --check names the package whose declaration and file disagree", () => {
  assert.match(problems({ [FEED]: null }), /molis-work-plugin-feed: package\.json declares a registration but plugins\/native\/feed\/src\/registration\.ts does not exist/);
  assert.match(problems(feedPackage(json => { delete json["molis-work"].registration; })), /molis-work-plugin-feed: has src\/registration\.ts but its package\.json does not declare it/);
  assert.match(problems(feedPackage(json => { json["molis-work"].registration = "./entry"; })), /"molis-work"\.registration must be "\.\/registration"/);
  assert.match(problems(feedPackage(json => { json.exports["./registration"] = "./dist/registration.js"; })), /exports "\.\/registration" must be \{ "types"/);
  assert.match(problems({ "plugins/native/stray/src/registration.ts": "export const registration = {};\n" }), /plugins\/native\/stray\/src\/registration\.ts belongs to no package in scripts\/workspace-packages\.mjs/);
});

test("W5-02-REG-02: --check refuses keys the contract does not have, at the top and in workbench", () => {
  assert.match(problems(feed("  manifest: feedManifest,", "  extra: true,\n  manifest: feedManifest,")), /has key "extra", which PluginRegistration does not declare/);
  assert.match(problems(feed("    order: 5,", "    order: 5,\n    placement: \"stage\",")), /has workbench key "placement", which PluginRegistration's workbench does not declare/);
  assert.match(problems(feed("  manifest: feedManifest,", "  ...{},\n  manifest: feedManifest,")), /has a member that is not a plain property \(\.\.\.\{\}\)/);
  assert.match(problems(feed("  manifest: feedManifest,", "  manifest: feedManifest,\n  manifest: feedManifest,")), /repeats key "manifest"/);
  assert.match(problems(feed("  workbench: {", "  workbench: WORKBENCH, _: {")), /must give "workbench" an object literal/);
  assert.match(problems(feed("export const registration: PluginRegistration =", "export let registration: PluginRegistration =")), /must declare `registration` with const/);
  assert.match(problems(feed("export const registration: PluginRegistration = {", "export const registration: PluginRegistration = REGISTRATION;\nconst REGISTRATION: PluginRegistration = {")), /must give `registration` an object literal/);
});

test("W5-02-REG-02: --check refuses a position or a key it cannot read, or one another plugin has", () => {
  assert.match(problems(feed("catalog_order: 10", "catalog_order: TEN")), /must give "catalog_order" a number literal/);
  const issues = BUILTIN_PLUGIN_CATALOG.find(entry => entry.project_plugin_id === "issues")!;
  assert.match(problems(feed("catalog_order: 10", `catalog_order: ${issues.catalog_order}`)), new RegExp(`catalog_order ${issues.catalog_order} is given by .+ and .+; each plugin needs its own`));
  assert.match(problems(feed("project_plugin_id: FEED_PROJECT_PLUGIN_ID", 'project_plugin_id: "Feed_Entries"')), /gives "project_plugin_id" "Feed_Entries", which is not a short id/);
  const literal = Object.fromEntries(["plugins/native/feed", "plugins/native/inbox"].map(dir => {
    const file = `${dir}/src/registration.ts`, text = readReal(file)!;
    return [file, text.replace(/project_plugin_id: [A-Z_]+,/, 'project_plugin_id: "same",')];
  }));
  assert.match(problems(literal), /project_plugin_id "same" is given by .+ and .+; each plugin needs its own/);
});

test("W5-02-REG-02: --check refuses a package under plugins/native/ that has no registration, even when its catalog entry was dropped with it", () => {
  const catalog = readReal(CATALOG_FILE)!;
  // What the generator used to write after someone deleted Feed's registration and its package.json declaration together:
  // a catalog that is consistent with the tree and simply has no Feed in it.
  const withoutFeed = catalog.replace(/^import \{ registration as feedRegistration \}.*\n/m, "").replace("  feedRegistration,\n", "");
  assert.notEqual(withoutFeed, catalog);
  const dropped = {
    ...feedPackage(json => { delete json["molis-work"].registration; delete json.exports["./registration"]; }),
    [FEED]: null,
    [CATALOG_FILE]: withoutFeed,
  };
  const named = /molis-work-plugin-feed: has no registration; every package under plugins\/native\/ writes plugins\/native\/feed\/src\/registration\.ts and declares it in package\.json/;
  assert.match(problems(dropped), named);
  assert.equal(pluginRegistry(tree(dropped), WORKSPACE_PACKAGES).text, null, "the generator writes nothing while a package is unregistered");
  // A new plugin that forgot its registration is the same case.
  const dir = "plugins/native/forgetful", name = "@molis-ai/molis-work-plugin-forgetful";
  const forgetful = { [`${dir}/package.json`]: `${JSON.stringify({ name, exports: { ".": { types: "./dist/index.d.ts", import: "./dist/index.js" } } }, null, 2)}\n` };
  assert.match(problems(forgetful, [...WORKSPACE_PACKAGES, { path: dir, name }]), /molis-work-plugin-forgetful: has no registration/);
  // Only a layout that has adopted registrations is asked: the scratch layouts of the gates' own tests list plugin packages and nothing else.
  const lone = { files: [], read: (file: string) => (file === `${dir}/package.json` ? forgetful[file] : null) };
  assert.deepEqual(pluginRegistryProblems(lone, [{ path: dir, name }]), []);
});

test("W5-02-REG-02: --check takes a catalog_order only as a positive integer literal", () => {
  const refused = (value: string, expected: RegExp) => assert.match(problems(feed("catalog_order: 10", `catalog_order: ${value}`)), expected, value);
  refused("0", /gives "catalog_order" 0, which is not a positive integer/);
  refused("1.5", /gives "catalog_order" 1\.5, which is not a positive integer/);
  refused("1e400", /gives "catalog_order" 1e400, which is not a positive integer/);
  refused("-1", /must give "catalog_order" a number literal, a positive integer/);
  refused("TEN", /must give "catalog_order" a number literal, a positive integer/);
  assert.doesNotMatch(problems(feed("catalog_order: 10", `catalog_order: ${NEXT_POSITION}`)), /catalog_order/, "an unused positive integer is accepted");
});

