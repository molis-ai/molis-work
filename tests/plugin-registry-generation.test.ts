// W5-02 (specs/repository-anti-corruption/privileges.md PG-065): each built-in plugin writes its catalog entry in its own
// src/registration.ts, and scripts/generate-plugin-registry.mjs writes apps/workbench/src/builtin-plugins.ts (the shell's
// resources) and apps/local-host/src/plugin-registry.generated.ts (the platform's list, W5-02 PR-B) from them. These tests drive
// the generator's pure functions on the repository's own tree with one file changed at a time, and the built catalog's validator
// on mutated copies. Isolated child processes also load the real public Host entry with bad catalogs supplied at the module
// loader boundary, proving that module initialization itself refuses them.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tracked = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" }).split("\0").filter(Boolean);
const FEED = "plugins/native/feed/src/registration.ts", FEED_PACKAGE = "plugins/native/feed/package.json";
const readReal = (file: string): string | null => { try { return readFileSync(path.join(root, file), "utf8"); } catch { return null; } };

type Entry = { path: string; name: string };
/** The repository as it is, with some files replaced (a string) or removed (null). */
function tree(changes: Record<string, string | null> = {}) {
  const files = [...new Set([...tracked, ...Object.keys(changes)])].filter(file => changes[file] !== null);
  return { files, read: (file: string) => (file in changes ? changes[file] : readReal(file)) ?? null };
}
const feed = (from: string, to: string) => {
  const text = readReal(FEED)!;
  assert.ok(text.includes(from), `${FEED} still has ${from}`);
  return { [FEED]: text.replace(from, to) };
};
type PackageJson = { "molis-work": Record<string, unknown>; exports: Record<string, unknown> };
const feedPackage = (edit: (json: PackageJson) => void) => {
  const json = JSON.parse(readReal(FEED_PACKAGE)!) as PackageJson;
  edit(json);
  return { [FEED_PACKAGE]: `${JSON.stringify(json, null, 2)}\n` };
};
/** The next free catalog position: they are positive integers, so a new plugin's is one past the highest. */
const NEXT_POSITION = Math.max(...BUILTIN_PLUGIN_CATALOG.map(entry => entry.catalog_order)) + 1;
const problems = (changes: Record<string, string | null>, packages: readonly Entry[] = WORKSPACE_PACKAGES) =>
  pluginRegistryProblems(tree(changes), packages).join("\n");

test("W5-02-REG-02: the repository's catalog is exactly the plugins' registrations, and --check says so", () => {
  assert.deepEqual(pluginRegistryProblems(tree(), WORKSPACE_PACKAGES), []);
  const run = spawnSync(process.execPath, ["scripts/generate-plugin-registry.mjs", "--check"], { cwd: root, encoding: "utf8" });
  assert.equal(run.status, 0, run.stderr);
  for (const file of [CATALOG_FILE, PLATFORM_FILE]) {
    const text = readReal(file)!;
    assert.match(text, /^\/\/ Generated by `node scripts\/generate-plugin-registry\.mjs`/, file);
    assert.equal(text.match(/^import \{ registration as \w+Registration \} from "[^"]+\/registration";$/gm)?.length, BUILTIN_PLUGIN_CATALOG.length, file);
  }
  const lines = (file: string) => readReal(file)!.split("\n").filter(line => line.startsWith("import {") || line.startsWith("  "));
  assert.deepEqual(lines(PLATFORM_FILE), lines(CATALOG_FILE), "RAC-567 the platform's list is the shell's, entry for entry");
});

test("W5-02-REG-02: --check fails on a catalog that is stale or edited by hand", () => {
  const catalog = readReal(CATALOG_FILE)!;
  const stale = /out of date or edited by hand; run node scripts\/generate-plugin-registry\.mjs/;
  assert.match(problems({ [CATALOG_FILE]: catalog.replace("  feedRegistration,\n", "") }), stale);
  assert.match(problems({ [CATALOG_FILE]: `${catalog}// a note\n` }), stale);
  assert.match(problems(feed("catalog_order: 10", "catalog_order: 999")), stale, "a moved entry reorders the generated list");
  assert.match(problems({ [CATALOG_FILE]: null }), stale, "a deleted catalog is not taken for a tree with nothing to list");
  // RAC-567: the platform's file is held to the same, on its own; either one stale, edited or missing fails.
  const platform = readReal(PLATFORM_FILE)!;
  const named = (changes: Record<string, string | null>) => problems(changes).split("\n").map(line => line.match(/registry: (\S+) is out of date/)?.[1]);
  assert.deepEqual(named({ [PLATFORM_FILE]: platform.replace("  feedRegistration,\n", "") }), [PLATFORM_FILE]);
  assert.deepEqual(named({ [PLATFORM_FILE]: `${platform}// a note\n` }), [PLATFORM_FILE]);
  assert.deepEqual(named({ [PLATFORM_FILE]: null }), [PLATFORM_FILE], "a missing platform list is not taken for one with nothing to list");
  assert.deepEqual(named({ [PLATFORM_FILE]: catalog }), [PLATFORM_FILE], "the shell's file under the platform's name is not the platform's list");
  assert.deepEqual(named(feed("catalog_order: 10", "catalog_order: 999")), [CATALOG_FILE, PLATFORM_FILE], "a moved entry makes both stale");
});

