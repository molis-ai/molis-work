import type { Child, Clip, ConfirmRecipe, Item, Recipe, RuntimeView, Shortcut, ShelfPage } from "./types.js";

const TEXT_EDIT = new Set(["txt", "md", "markdown", "json", "swift", "py", "js", "ts", "mjs", "css", "yaml", "yml", "xml", "toml", "ini", "rs", "go", "rb", "sh", "zsh", "c", "h", "cc", "cpp", "m", "mm", "csv", "log"]);
const extOf = (name: string): string => String(name || "").split(".").pop()?.toLowerCase() ?? "";

export const hasFile = (item: Item | null | undefined): item is Item => Boolean(item && item.relative_path);
export const isFailed = (item: Item | null | undefined): boolean => Boolean(item && item.status === "failed");

export const isEditable = (item: Item | null | undefined): boolean => {
  if (!item) return false;
  if (item.kind === "pdf" || item.kind === "image" || item.kind === "folder" || item.kind === "url" || item.kind === "website") return false;
  const ext = extOf(item.name);
  if (ext === "html" || ext === "htm") return false;
  if (item.kind === "markdown" || item.kind === "text") return true;
  return TEXT_EDIT.has(ext);
};

export const isConcealed = (types: readonly string[]): boolean => types.some((type) => /org\.nspasteboard\.(concealedtype|autogeneratedtype|transienttype)/i.test(String(type)));

const CAPS: Record<string, string> = { pdf: "PDF", markdown: "MD", text: "TXT", image: "IMG", website: "WEB", url: "URL", folder: "DIR" };
export const cap = (kind: string): string => CAPS[kind] ?? "FILE";

export const clockLabel = (stamp: string | undefined): string => {
  const when = new Date(stamp || "");
  if (Number.isNaN(when.getTime())) return "";
  return when.getHours() + ":" + String(when.getMinutes()).padStart(2, "0");
};

export const tone = (kind: string, group: string): string => {
  if (group === "clipboard") return kind === "url" ? "blue" : "slate";
  if (kind === "pdf") return "clay";
  if (kind === "image") return "plum";
  if (kind === "url" || kind === "website") return "blue";
  if (kind === "markdown" || kind === "text") return "slate";
  return "ochre";
};

export const items = (page: ShelfPage): Item[] => [...(page.snapshot.materials || []), ...(page.snapshot.results || [])];
export const itemById = (page: ShelfPage, id: string | null | undefined): Item | undefined => items(page).find((item) => item.item_id === id);
export const clipById = (page: ShelfPage, id: string): Clip | undefined => (page.snapshot.clipboard || []).find((clip) => clip.clip_id === id);
export const stageBusy = (page: ShelfPage): boolean => ["is-confirm", "is-run", "is-fail"].some((name) => page.stage.classList.contains(name));
export const batch = (page: ShelfPage): Item[] => page.selClip ? [] : items(page).filter((item) => page.selection.has(item.item_id));

export const runtime = (page: ShelfPage): RuntimeView => page.snapshot.runtime || { runtime_key: "", title: "Agent", can_run_job: false, isolation: "none", isolation_fact: "" };
export const ai = (page: ShelfPage) => page.snapshot.ai || { available: false, reason: null, choices: [], selected: null };
export const agentMissing = (page: ShelfPage): boolean => !ai(page).available;
export const aiLabel = (page: ShelfPage): string => {
  const { choices, selected } = ai(page);
  return choices.find((choice) => choice.provider_id === selected?.provider_id && choice.model_id === selected?.model_id)?.label || page.L("shelf.model.ai-model");
};

export const recipeList = (page: ShelfPage): readonly Recipe[] => page.snapshot.recipes || [];
export const recipeFor = (page: ShelfPage, id: string): Recipe | null => recipeList(page).find((entry) => entry.recipe === id) || null;
export const actIdFor = (recipe: string): string => recipe === "extract_text" ? "extract" : recipe;
export const recipeForAct = (page: ShelfPage, actId: string): Recipe | null => recipeFor(page, actId === "extract" ? "extract_text" : actId);
export const chosenOption = (page: ShelfPage, recipe: { recipe: string; default_choice?: string }): string | null => page.choices[recipe.recipe] || recipe.default_choice || null;
export const isLocalRecipe = (recipe: { requires_agent?: boolean } | null | undefined): boolean => Boolean(recipe) && recipe?.requires_agent === false;

export const deviceSettings = (page: ShelfPage) => page.snapshot.settings;
export const actionOrder = (page: ShelfPage): string[] => {
  const order = deviceSettings(page)?.action_order;
  return Array.isArray(order) && order.length ? [...order] : recipeList(page).map((entry) => entry.recipe);
};
export const hiddenActions = (page: ShelfPage): Set<string> => new Set(deviceSettings(page)?.hidden_actions || []);
export const shortcutActions = (page: ShelfPage): readonly Shortcut[] => deviceSettings(page)?.shortcuts || [];
export const shortcutFor = (page: ShelfPage, slot: string): Shortcut | null => shortcutActions(page).find((action) => "shortcut:" + action.id === slot) || null;

export function matchesPanelKey(page: ShelfPage, event: KeyboardEvent, slot: "hide" | "paste" | "copy" | "delete"): boolean {
  const chord = deviceSettings(page)?.panel_keys?.[slot];
  if (!chord) return false;
  return event.code === chord.code && event.metaKey === Boolean(chord.meta) && event.ctrlKey === Boolean(chord.ctrl)
    && event.altKey === Boolean(chord.alt) && event.shiftKey === Boolean(chord.shift);
}

/** The recipe the confirmation drawer shows: the pending one, or one made up of a shortcut action's own words. */
export function confirmRecipe(page: ShelfPage): ConfirmRecipe | null {
  const { pending, L } = page;
  if (!pending) return null;
  const { shortcut } = pending;
  if (shortcut) {
    return {
      recipe: "shortcut", label: shortcut.name, short_title: shortcut.name, blurb: L("shelf.bar.run-on-a-copy-and"), tone: "ochre",
      accepts: shortcut.kinds || [], output_file: "", needs_network: true, requires_agent: true, minimum_count: 1, choices: [], default_choice: "",
    };
  }
  return recipeFor(page, pending.recipe);
}

export const filePathOf = (page: ShelfPage, item: Item | undefined): string => {
  const root = page.snapshot.root || "";
  return root && item?.relative_path ? root + "/" + item.relative_path : "";
};
export const quotePath = (value: string): string => "'" + String(value).replaceAll("'", String.fromCharCode(39, 92, 39, 39)) + "'";

export const fileUrl = (page: ShelfPage, id: string): string => page.api + "/items/" + encodeURIComponent(id) + "/file";
export const childUrl = (page: ShelfPage, itemId: string, relative: string): string => fileUrl(page, itemId) + "?child=" + encodeURIComponent(relative);

/** The folder's file at `relative`. */
export const childOf = (item: Item, relative: string): Child | undefined => (item.children || []).find((entry) => entry.relative === relative);

export function comparisonSources(page: ShelfPage): Item[] {
  const { selected } = page;
  const ids = selected?.source_item_ids?.length ? selected.source_item_ids : [selected?.source_item_id].filter((id): id is string => Boolean(id));
  return ids.map((id) => itemById(page, id)).filter((item): item is Item => Boolean(item));
}
