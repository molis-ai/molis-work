import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");
const load = (p) => import(pathToFileURL(path.join(root, p)).href);
const pageAssets = await load("apps/workbench/dist/page-assets.js");
const catalog = await load("apps/workbench/dist/primitive-catalog.js");
const icons = await load("packages/design-system/dist/icons.js");
const ring = await load("packages/design-system/dist/state-ring-client.js");

const PARTS = ["mw-btn", "mw-compose", "mw-menu", "mw-textarea", "mw-field", "mw-input", "mw-kbd", "mw-badge", "mw-alert",
  "mw-toast", "mw-spinner", "mw-state-ring", "mw-tooltip", "mw-popover", "mw-sr-only", "mw-toggle", "mw-check", "mw-hint",
  "mw-status", "mw-receipt", "mw-select", "mw-drop", "mw-mark", "mw-upload", "mw-uploads", "mw-progress", "mw-btn-group",
  "mw-tag", "mw-tags", "mw-empty"];
// Base rules the parts rely on (icon strokes, the hidden sprite), kept by exact selector.
const BASE = new Set(["svg", ".icon-sprite"]);
const DROP = [".mw-catalog", "body.", "#", ".assistant", ".workbench", ".bar-", ".mw-ix", "[data-pane", ".immersive"];
const ICONS = ["paperclip", "send", "x", "chevron-down", "clock", "alert", "circle-alert", "check", "zap", "plus", "file", "image",
  "book", "message", "pause", "list", "refresh", "undo", "info", "arrow", "target", "waiting", "package", "cloud", "hash", "user", "more", "upload", "sparkles", "chevron-right", "search", "bell"];

/** Splits a stylesheet into top-level blocks, keeping nested at-rules as text to recurse into. */
function blocks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === "{") depth++; else if (css[j] === "}") depth--; j++; }
    out.push({ head: head.replace(/\/\*[\s\S]*?\*\//g, "").trim(), body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}
const isToken = (sel) => /^(:root|html\[data-resolved-theme="dark"\](\s*:root)?|:root\[data-resolved-theme="dark"\])$/.test(sel.trim());
// A rule is kept when its selector names one of PARTS outside :not() and names no class other than mw-* parts and is-* states, so
// plugin- and page-scoped overrides (".goal-… .mw-btn", "textarea:not(.mw-textarea)") stay behind.
const wanted = (sel) => {
  const bare = sel.replace(/:not\((?:[^()]|\([^()]*\))*\)/g, "");
  return PARTS.some((p) => new RegExp(`\\.${p}(?![a-z0-9-])|\\.${p}--|\\.${p}__`).test(bare))
    && !/\.(?!mw-|is-)[a-zA-Z_]/.test(sel) && !DROP.some((d) => sel.includes(d));
};
const keptFrames = new Set();
function pick(css) {
  let out = "";
  for (const { head, body } of blocks(css)) {
    if (!head) continue;
    if (head.startsWith("@font-face") || head.startsWith("@import")) continue;
    if (head.startsWith("@keyframes")) { out += `\u0000${head}{${body}}\n`; continue; }
    if (head.startsWith("@")) { const inner = pick(body); if (inner.trim()) out += `${head}{\n${inner}}\n`; continue; }
    const sels = head.split(/,(?![^(]*\))/).map((s) => s.trim());
    const tokens = sels.filter(isToken);
    if (tokens.length) { out += `${tokens.join(",")}{${body}}\n`; continue; }
    const keep = sels.filter((sel) => BASE.has(sel) || wanted(sel));
    if (keep.length) {
      out += `${keep.join(",")}{${body}}\n`;
      for (const m of body.matchAll(/animation(?:-name)?\s*:\s*([^;]+)/g)) for (const w of m[1].split(/[\s,]+/)) keptFrames.add(w);
    }
  }
  return out;
}
const boardHtml = catalog.renderMolisWorkPrimitiveCatalog();
const inline = [...boardHtml.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
let css = pick(pageAssets.renderMolisWorkWorkbenchStylesheet() + "\n" + inline);
css = css.replace(/\u0000(@keyframes\s+([\w-]+)[^\n]*)\n/g, (all, block, name) => (keptFrames.has(name) ? block + "\n" : ""));
const sha = process.env.GIT_SHA || "";
writeFileSync(path.join(here, "board.css"), `/* Generated by extract-board.mjs from the built workbench stylesheet and the component board${sha ? ` at ${sha}` : ""}. Do not edit. */\n${css}`);

const sprite = icons.renderIconSprite();
const symbols = ICONS.map((n) => sprite.match(new RegExp(`<symbol id="icon-${n}"[\\s\\S]*?</symbol>`))?.[0]).filter(Boolean);
writeFileSync(path.join(here, "board-icons.js"), `// Generated by extract-board.mjs from the design system's icon sprite. Do not edit.\nwindow.boardIcons = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" class="icon-sprite" aria-hidden="true">${symbols.join("")}</svg>`)};\n`);
writeFileSync(path.join(here, "board-ring.js"), `// Generated by extract-board.mjs from the design system's state-ring client. Do not edit.\n${ring.STATE_RING_CLIENT_SCRIPT}\n`);
console.log(`board.css ${css.length} bytes; ${symbols.length}/${ICONS.length} icons`);
