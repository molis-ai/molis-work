// Rebuilds kit/ from the component board's own code, so this prototype is drawn with the shipped parts.
// Run after `pnpm build` (it reads the built design-system and plugin-sdk):
//   node docs/design/coding-execution-states/kit/build.mjs
// Writes kit.css (VISUAL_FOUNDATION_STYLES: tokens, mw-* primitives, toast, state ring; plus MOTION_STYLES: the four entrances and the landed wash),
// kit.js (theme bootstrap, the visual foundation client script, the icon sprite, and the real renderers as window.mwKit).
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../../..");
const ds = await import(join(root, "packages/design-system/dist/index.js"));
const { MOTION_STYLES } = await import(join(root, "packages/design-system/dist/styles/motion.js"));

writeFileSync(join(here, "kit.css"), `/* Generated by kit/build.mjs from packages/design-system (VISUAL_FOUNDATION_STYLES + MOTION_STYLES). Do not edit. */\n${ds.VISUAL_FOUNDATION_STYLES}${MOTION_STYLES}`);

const entry = `
import { renderButton, renderStatusMark, renderBadge, renderAlert, renderStateRing, icon, escapeHtml } from ${JSON.stringify(join(root, "packages/plugin-sdk/dist/ui.js"))};
import { renderMenu, renderMenuItem, renderMenuGroup } from ${JSON.stringify(join(root, "packages/design-system/dist/primitives/overlay.js"))};
import { renderToggleGroup } from ${JSON.stringify(join(root, "packages/design-system/dist/primitives/navigation.js"))};
import { renderFileKind } from ${JSON.stringify(join(root, "packages/design-system/dist/primitives/arrival.js"))};
window.mwKit = { renderButton, renderStatusMark, renderBadge, renderAlert, renderStateRing, icon, escapeHtml, renderMenu, renderMenuItem, renderMenuGroup, renderToggleGroup, renderFileKind };
`;
const out = await build({ stdin: { contents: entry, resolveDir: root, loader: "js" }, bundle: true, write: false, format: "iife", platform: "browser", minify: true, logLevel: "silent" });
const renderers = out.outputFiles[0].text;
const sprite = ds.renderIconSprite();
writeFileSync(join(here, "kit.js"), `/* Generated by kit/build.mjs from packages/design-system and packages/plugin-sdk. Do not edit. */
${ds.THEME_BOOTSTRAP_SCRIPT}
${renderers}
window.mwKitSprite = ${JSON.stringify(sprite)};
window.mwKitClient = ${JSON.stringify(ds.VISUAL_FOUNDATION_CLIENT_SCRIPT)};
`);
console.log("kit.css", ds.VISUAL_FOUNDATION_STYLES.length, "kit.js", renderers.length + sprite.length + ds.VISUAL_FOUNDATION_CLIENT_SCRIPT.length);
