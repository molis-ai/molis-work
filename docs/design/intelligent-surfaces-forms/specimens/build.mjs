// Design-only bridge. It bundles the owning source functions; it does not change SDK exports.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { readFileSync } from 'node:fs';
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../../..');
const require = createRequire(resolve(process.env.SPECIMEN_TOOL_ROOT || root, 'package.json'));
const { build } = require('esbuild');
const font=JSON.parse(readFileSync(resolve(root,'packages/design-system/resources/fonts/system-sans.json'),'utf8'));
const fontRoles=`:root{--weight-body:${font.roles.body.weight};--weight-control:${font.roles.control.weight};--weight-title:${font.roles.title.weight};--tracking-body:${font.roles.body.tracking_em}em;--tracking-title:${font.roles.title.tracking_em}em}`;
await build({
  stdin: { contents: `
import { renderPreviewCard, renderSheet } from '${root}/packages/design-system/src/primitives/overlay.ts';
import { CATALOG_PATTERN_STYLES } from '${root}/packages/design-system/src/primitives/catalog-patterns.ts';
Object.assign(window.mwKit, { renderPreviewCard, renderSheet });
const sheet = document.createElement('style'); sheet.textContent = CATALOG_PATTERN_STYLES + ${JSON.stringify(fontRoles)}; document.head.append(sheet);
`, resolveDir: root, loader: 'ts' },
  plugins: [{ name: 'existing-kit', setup(build) {
    build.onResolve({ filter: /^@molis-ai\/molis-work-plugin-sdk\/ui$/ }, () => ({ path: 'kit', namespace: 'specimen' }));
    build.onLoad({ filter: /.*/, namespace: 'specimen' }, () => ({ resolveDir: root, loader: 'ts', contents: `
export { cx, escapeHtml, renderAttrs } from '${root}/packages/plugin-sdk/src/ui/html.ts';
export { renderMenu, renderMenuItem, renderPopover, renderPreviewCard, renderSheet } from '${root}/packages/plugin-sdk/src/ui/overlay.ts';
export const { icon, renderButton, renderCheckbox, renderInput, renderInputGroup, renderProgress, renderSelect, renderStatusMark, renderSwitch } = window.mwKit;
` }));
  }}],
  bundle: true, treeShaking: true, minify: false, format: 'iife', platform: 'browser',
  outfile: resolve(here, 'parts.generated.js'),
  banner: { js: '// Generated by specimens/build.mjs from the owning DS source. Do not edit.' },
});
