#!/usr/bin/env node
// The structure snapshot of every library this build creates (UPG-01; specs/upgrade-continuity/golden-replay-design.md §5), written down in
// tooling/gates/schemas/stores.tsv the way tooling/gates/actions/ holds the action contracts. scripts/gates/store-schemas.mjs compares the file
// with the merge-base's in `pnpm health:check`; this half says whether the file is what the built product creates.
//
//   node scripts/gates/store-schema-snapshot.mjs            check: exit 1 when the file and the product differ
//   node scripts/gates/store-schema-snapshot.mjs --update   rewrite the file (pnpm schemas:update)
//
// The check also runs in `pnpm test:contracts` (tests/store-schema-snapshot.test.ts). It needs the packages built; it starts no Host and opens
// no Home: each baseline's statements run in an in-memory SQLite.
//
// WHICH LIBRARIES. The project catalog and the project database; every Home library of the Host's store registry (`homeStores()`, which
// already holds each built-in plugin's `databases.home`); each built-in plugin's project tables (`databases.project`), under the project
// database's pattern with `#<plugin_id>`; and the old Alchemist's two stores, which stay at version 1 with their own refusal (BL-377).
// An installed plugin's library is the publisher's, not this build's, so it is not here.
//
// THE HASH. sha256 (first 16 digits) of what SQLite itself reports after running the statements: `describeSqliteSchema` (tables, columns,
// checks, foreign keys, indexes, the comparison a Home's open makes) and every trigger and view with its statement, spaces squashed. So
// reformatting a statement or editing a comment outside a trigger changes nothing, and anything a Home in use would keep in its old form does.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";
import { parseStoreSchemas, SCHEMA_COLUMNS, SCHEMAS_FILE } from "./store-schemas.mjs";
import { isMainScript } from "../script-paths.mjs";

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const HEADER = [
  "# Library structure snapshot (UPG-01, specs/upgrade-continuity/golden-replay-design.md §5): one row per library this build creates.",
  "# Generated by `node scripts/gates/store-schema-snapshot.mjs --update` (pnpm schemas:update); do not edit by hand. structure is a hash of what",
  "# SQLite reports after running the creation statements; upgrades is the `from` of each step, or -. scripts/gates/store-schemas.mjs fails a",
  "# row whose structure changed while its version stayed.",
];

const squash = text => String(text ?? "").replace(/\s+/gu, " ").trim();

/** The hash of a baseline's structure. `describe` is the storage package's `describeSqliteSchema`. */
export function structureHash(schema, describe) {
  const db = new DatabaseSync(":memory:");
  try {
    db.exec(schema);
    const objects = db.prepare("SELECT type, name, tbl_name AS owner, sql FROM sqlite_master WHERE type IN ('trigger', 'view') ORDER BY type, name").all()
      .map(row => [row.type, row.name, row.owner, squash(row.sql)]);
    return createHash("sha256").update(JSON.stringify({ tables: describe(db).tables, objects })).digest("hex").slice(0, 16);
  } finally { db.close(); }
}

const froms = baseline => (baseline.upgrades ?? []).map(step => step.from).sort((left, right) => left - right);

/** Every library of the built product, sorted by `store`. */
export async function productRows() {
  const host = await import("@molis-ai/molis-work-app-local-host");
  const { describeSqliteSchema } = await import("@molis-ai/molis-work-storage");
  const row = (store, owner, baseline) => {
    try { return { store, owner, version: baseline.version, structure: structureHash(baseline.schema, describeSqliteSchema), froms: froms(baseline) }; }
    catch (error) { throw new Error(`${store}: its creation statements do not run on their own: ${error instanceof Error ? error.message : String(error)}`); }
  };
  const rows = [
    row("projects/catalog.db", "apps/local-host", host.CATALOG_BASELINE),
    row("projects/*/molis-work.db", "apps/local-host", host.PROJECT_DATABASE_BASELINE),
    row("alchemist/projects/*/studio.sqlite", "apps/local-host", host.ALCHEMIST_STUDIO_BASELINE),
    row("alchemist/projects/*/search.sqlite", "apps/local-host", host.ALCHEMIST_SEARCH_BASELINE),
    ...host.homeStores().stores.filter(store => store.library).map(store => {
      const name = store.library.file ?? `${store.path}.db`;
      return row(store.library.partition ? `${store.path}/projects/*/${name}` : `${store.path}/${name}`, store.owner, store.library.baseline);
    }),
    ...host.PLATFORM_PLUGIN_REGISTRATIONS.filter(entry => entry.manifest.databases?.project).map(entry =>
      row(`projects/*/molis-work.db#${entry.manifest.plugin_id}`, entry.manifest.plugin_id, entry.manifest.databases.project)),
  ];
  return rows.sort((left, right) => (left.store < right.store ? -1 : left.store > right.store ? 1 : 0));
}

/** The file's text for these rows. */
export const renderStoreSchemas = rows => [...HEADER, SCHEMA_COLUMNS.join("\t"),
  ...rows.map(row => [row.store, row.owner, row.version, row.structure, row.froms.length ? row.froms.join(",") : "-"].join("\t")), ""].join("\n");

/** What differs between the committed text and the product, one sentence per library; empty when they agree. */
export function snapshotDifferences(text, rows) {
  if (text === null) return [`${SCHEMAS_FILE} is missing; write it with \`pnpm schemas:update\``];
  const committed = parseStoreSchemas(text);
  if (committed.why) return [committed.why];
  const problems = [], seen = new Set();
  for (const row of rows) {
    seen.add(row.store);
    const found = committed.rows.get(row.store);
    if (!found) { problems.push(`${row.store} is not in ${SCHEMAS_FILE}`); continue; }
    const changed = ["owner", "version", "structure"].filter(key => String(found[key]) !== String(row[key]));
    if (found.froms.join(",") !== row.froms.join(",")) changed.push("upgrades");
    if (changed.length) problems.push(`${row.store}: ${changed.join(", ")} differ from ${SCHEMAS_FILE}`);
  }
  for (const store of committed.rows.keys()) if (!seen.has(store)) problems.push(`${store} is in ${SCHEMAS_FILE}, and the product has no such library`);
  if (!problems.length && text !== renderStoreSchemas(rows)) problems.push(`${SCHEMAS_FILE} holds the right rows but is not written the way \`pnpm schemas:update\` writes it`);
  return problems;
}

if (isMainScript(import.meta.url)) {
  const file = path.join(repository, SCHEMAS_FILE), rows = await productRows();
  if (process.argv.includes("--update")) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, renderStoreSchemas(rows));
    console.log(`${SCHEMAS_FILE}: ${rows.length} libraries`);
    process.exit(0);
  }
  let text = null;
  try { text = readFileSync(file, "utf8"); } catch (error) { if (error?.code !== "ENOENT") throw error; }
  const problems = snapshotDifferences(text, rows);
  if (problems.length) {
    console.error(`The library structure snapshot is out of date; run \`pnpm schemas:update\` and commit ${SCHEMAS_FILE}:\n- ${problems.join("\n- ")}`);
    process.exit(1);
  }
  console.log(`${SCHEMAS_FILE}: ${rows.length} libraries, as the product creates them`);
  process.exit(0);
}
