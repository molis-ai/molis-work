test("W5-02-REG-02: the built catalog has no repeated key, Manifest id or position, and every id it names is in it", () => {
  assert.deepEqual(catalogProblems(BUILTIN_PLUGIN_CATALOG), []);
  const feedEntry = BUILTIN_PLUGIN_CATALOG.find(entry => entry.project_plugin_id === "feed")!;
  const coding = BUILTIN_PLUGIN_CATALOG.find(entry => entry.workbench.clientUses?.length)!;
  const without = (id: string) => BUILTIN_PLUGIN_CATALOG.filter(entry => entry.project_plugin_id !== id);
  const cases: Array<[string, readonly PluginRegistration[], RegExp]> = [
    ["repeated key", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, catalog_order: 9999, manifest: { ...feedEntry.manifest, plugin_id: "io.molis.copy" } }], /two plugins have the project key feed/],
    ["repeated Manifest id", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", catalog_order: 9999 }], new RegExp(`two plugins have the Manifest id ${feedEntry.manifest.plugin_id.replaceAll(".", "\\.")}`)],
    ["repeated position", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", manifest: { ...feedEntry.manifest, plugin_id: "io.molis.copy" } }], new RegExp(`two plugins have the catalog position ${feedEntry.catalog_order}`)],
    ["dangling companion", without("inbox"), /feed names inbox in companions, which is not in the catalog/],
    ["dangling clientUses", without(coding.workbench.clientUses![0]!), new RegExp(`${coding.project_plugin_id} names ${coding.workbench.clientUses![0]} in workbench.clientUses, which is not in the catalog`)],
    // PG-070 RAC-767: a plugin's extra class prefixes decide what leaves the shared sheet, so one catalog entry may not take
    // another plugin's id or the platform's own prefixes, and the same prefix cannot be listed twice or by two plugins.
    ["prefix is not a class prefix", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", workbench: { ...feedEntry.workbench, stylesheetPrefixes: ["As-"] } }], /copy: stylesheet prefix As- is not a lowercase class prefix ending in -/],
    ["prefix takes the platform's", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", workbench: { ...feedEntry.workbench, stylesheetPrefixes: ["mw-"] } }], /copy: stylesheet prefix mw- is the platform's/],
    ["prefix repeats a plugin's id", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", workbench: { ...feedEntry.workbench, stylesheetPrefixes: ["inbox-"] } }], /copy: stylesheet prefix inbox- repeats a plugin's id/],
    ["prefix listed twice", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", workbench: { ...feedEntry.workbench, stylesheetPrefixes: ["cd-", "cd-"] } }], /copy lists stylesheet prefix cd- twice/],
    ["two plugins claim one prefix", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", workbench: { ...feedEntry.workbench, stylesheetPrefixes: ["shared-"] } }, { ...feedEntry, project_plugin_id: "copy2", catalog_order: 9999, manifest: { ...feedEntry.manifest, plugin_id: "io.molis.copy2" }, workbench: { ...feedEntry.workbench, stylesheetPrefixes: ["shared-"] } }], /copy and copy2 both claim stylesheet prefix shared-/],
  ];
  for (const [label, catalog, expected] of cases) assert.match(catalogProblems(catalog).join("\n"), expected, label);
});

test("W5-02-REG-02: loading the Host rejects an invalid catalog before the module becomes available", () => {
  const runner = `
    import { registerHooks } from "node:module";
    const target = new URL("./plugin-registry.generated.js", import.meta.resolve("@molis-ai/molis-work-app-local-host")).href;
    registerHooks({ load(url, context, nextLoad) {
      const loaded = nextLoad(url, context);
      if (url !== target || process.argv[1] === "valid") return loaded;
      const source = typeof loaded.source === "string" ? loaded.source : new TextDecoder().decode(loaded.source);
      const mutation = process.argv[1] === "duplicate"
        ? "PLATFORM_PLUGIN_REGISTRATIONS.push({ ...PLATFORM_PLUGIN_REGISTRATIONS[0] });"
        : 'PLATFORM_PLUGIN_REGISTRATIONS.splice(0, 1, { ...PLATFORM_PLUGIN_REGISTRATIONS[0], companions: ["missing-catalog-dependency"] });';
      return { ...loaded, source: source + "\\n" + mutation };
    } });
    await import("@molis-ai/molis-work-app-local-host");
    process.stdout.write("host loaded");
  `;
  const load = (mode: string) => spawnSync(process.execPath, ["--input-type=module", "--eval", runner, mode], {
    cwd: root, encoding: "utf8", timeout: 30_000,
  });
  const valid = load("valid");
  assert.equal(valid.status, 0, valid.stderr);
  assert.equal(valid.stdout, "host loaded");
  for (const [mode, expected] of [
    ["duplicate", /Built-in plugin catalog: two plugins have the project key /],
    ["dangling", /Built-in plugin catalog: .* names missing-catalog-dependency in companions, which is not in the catalog/],
  ] as const) {
    const invalid = load(mode);
    assert.equal(invalid.status, 1, invalid.stderr);
    assert.match(invalid.stderr, expected);
    assert.equal(invalid.stdout, "", "the public module must not finish loading");
  }
});

test("RAC-572 (the two apps; the root comes with PR-C): an app's package.json is not counted only while its plugin dependencies are exactly what its generated file imports", async () => {
  const { generatedMentionFiles } = await import("../scripts/gates/assembly.mjs");
  const plugins = new Set(["@fx/plugin-one", "@fx/plugin-two", "@fx/plugin-three"]);
  const generated = (...names: string[]) => names.map(name => `import { registration as x } from "${name}/registration";\n`).join("");
  const manifest = (...names: string[]) => JSON.stringify({ dependencies: Object.fromEntries([...names, "@fx/storage"].map(name => [name, "workspace:*"])) });
  const exempt = (files: Record<string, string>) => [...generatedMentionFiles({ read: (file: string) => files[file] ?? null }, plugins)].sort();
  const workbench = { "apps/workbench/src/builtin-plugins.ts": generated("@fx/plugin-one", "@fx/plugin-two") };
  assert.deepEqual(exempt({ ...workbench, "apps/workbench/package.json": manifest("@fx/plugin-one", "@fx/plugin-two") }),
    ["apps/workbench/package.json", "apps/workbench/src/builtin-plugins.ts"], "the same set: neither is counted");
  assert.deepEqual(exempt({ ...workbench, "apps/workbench/package.json": manifest("@fx/plugin-one", "@fx/plugin-two", "@fx/plugin-three") }),
    ["apps/workbench/src/builtin-plugins.ts"], "one more plugin dependency than the file imports: the manifest is counted");
  assert.deepEqual(exempt({ ...workbench, "apps/workbench/package.json": manifest("@fx/plugin-one") }),
    ["apps/workbench/src/builtin-plugins.ts"], "one fewer: the manifest is counted");
  assert.deepEqual(exempt({ "apps/local-host/package.json": manifest() }), [], "without its generated file an app's manifest is counted");
});

test("W5-02-REG-03: a new plugin is its own package; the generator lists it and nothing else changes by hand", () => {
  const dir = "plugins/native/future", name = "@molis-ai/molis-work-plugin-future";
  const packages = [...WORKSPACE_PACKAGES, { path: dir, name }];
  const own = {
    [`${dir}/package.json`]: `${JSON.stringify({ name, exports: { ".": { types: "./dist/index.d.ts", import: "./dist/index.js" }, "./registration": { types: "./dist/registration.d.ts", import: "./dist/registration.js" } }, "molis-work": { registration: "./registration" } }, null, 2)}\n`,
    [`${dir}/src/registration.ts`]: readReal(FEED)!.replace(/catalog_order: \d+/, `catalog_order: ${NEXT_POSITION}`).replace("project_plugin_id: FEED_PROJECT_PLUGIN_ID", 'project_plugin_id: "future"').replace(/companions: \[[^\]]*\],?\n/, ""),
  };
  assert.match(problems(own, packages), /out of date or edited by hand/, "the catalog does not list it until regenerated");
  const { text, platformText, problems: refused } = pluginRegistry(tree(own), packages);
  assert.deepEqual(refused, []);
  assert.ok(text);
  assert.match(text, /^import \{ registration as futureRegistration \} from "@molis-ai\/molis-work-plugin-future\/registration";$/m);
  const listed = text.split("\n").filter(line => line.startsWith("  ")).map(line => line.trim().replace(/,$/, ""));
  assert.equal(listed.indexOf("futureRegistration"), BUILTIN_PLUGIN_CATALOG.length, "listed by catalog_order (after the last plugin), not by package name");
  assert.match(problems({ ...own, [CATALOG_FILE]: text }, packages), /plugin-registry\.generated\.ts is out of date/, "the platform's list too");
  assert.deepEqual(problems({ ...own, [CATALOG_FILE]: text, [PLATFORM_FILE]: platformText }, packages), "",
    "its package and the two regenerated files are the whole change");
});
