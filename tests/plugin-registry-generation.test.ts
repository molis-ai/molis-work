import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import type { PluginRegistration } from "@molis-ai/molis-work-contracts/platform/plugin-registration";
import { BUILTIN_PLUGIN_CATALOG, catalogProblems } from "@molis-ai/molis-work-app-workbench";
import { CATALOG_FILE, pluginRegistry, pluginRegistryProblems } from "../scripts/generate-plugin-registry.mjs";
import { WORKSPACE_PACKAGES } from "../scripts/workspace-packages.mjs";

// W5-02 (specs/repository-anti-corruption/privileges.md PG-065): each built-in plugin writes its catalog entry in its own
// src/registration.ts, and scripts/generate-plugin-registry.mjs writes apps/workbench/src/builtin-plugins.ts from them. These
// tests drive the generator's pure functions on the repository's own tree with one file changed at a time, and the built
// catalog's load-time check (apps/workbench/src/plugin-catalog.ts) on mutated copies of the built catalog.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tracked = execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8" }).split("\n").filter(Boolean);
const FEED = "plugins/native/feed/src/registration.ts", FEED_PACKAGE = "plugins/native/feed/package.json";
const readReal = (file: string): string | null => { try { return readFileSync(path.join(root, file), "utf8"); } catch { return null; } };

type Entry = { path: string; name: string };
/** The repository as it is, with some files replaced (a string) or removed (null). */
function tree(changes: Record<string, string | null> = {}) {
  const files = [...new Set([...tracked, ...Object.keys(changes)])].filter(file => changes[file] !== null);
  return { files, read: (file: string) => (file in changes ? changes[file] : readReal(file)) ?? null };
}
const feed = (from: string, to: string) => {
  const text = readReal(FEED)!;
  assert.ok(text.includes(from), `${FEED} still has ${from}`);
  return { [FEED]: text.replace(from, to) };
};
type PackageJson = { "molis-work": Record<string, unknown>; exports: Record<string, unknown> };
const feedPackage = (edit: (json: PackageJson) => void) => {
  const json = JSON.parse(readReal(FEED_PACKAGE)!) as PackageJson;
  edit(json);
  return { [FEED_PACKAGE]: `${JSON.stringify(json, null, 2)}\n` };
};
const problems = (changes: Record<string, string | null>, packages: readonly Entry[] = WORKSPACE_PACKAGES) =>
  pluginRegistryProblems(tree(changes), packages).join("\n");

test("W5-02-REG-02: the repository's catalog is exactly the plugins' registrations, and --check says so", () => {
  assert.deepEqual(pluginRegistryProblems(tree(), WORKSPACE_PACKAGES), []);
  const run = spawnSync(process.execPath, ["scripts/generate-plugin-registry.mjs", "--check"], { cwd: root, encoding: "utf8" });
  assert.equal(run.status, 0, run.stderr);
  const catalog = readReal(CATALOG_FILE)!;
  assert.match(catalog, /^\/\/ Generated by `node scripts\/generate-plugin-registry\.mjs`/);
  assert.equal(catalog.match(/^import \{ registration as \w+Registration \} from "[^"]+\/registration";$/gm)?.length, BUILTIN_PLUGIN_CATALOG.length);
});

test("W5-02-REG-02: --check fails on a catalog that is stale or edited by hand", () => {
  const catalog = readReal(CATALOG_FILE)!;
  const stale = /out of date or edited by hand; run node scripts\/generate-plugin-registry\.mjs/;
  assert.match(problems({ [CATALOG_FILE]: catalog.replace("  feedRegistration,\n", "") }), stale);
  assert.match(problems({ [CATALOG_FILE]: `${catalog}// a note\n` }), stale);
  assert.match(problems(feed("catalog_order: 10", "catalog_order: 999")), stale, "a moved entry reorders the generated list");
  assert.match(problems({ [CATALOG_FILE]: null }), stale, "a deleted catalog is not taken for a tree with nothing to list");
});

test("W5-02-REG-02: --check names the package whose declaration and file disagree", () => {
  assert.match(problems({ [FEED]: null }), /molis-work-plugin-feed: package\.json declares a registration but plugins\/native\/feed\/src\/registration\.ts does not exist/);
  assert.match(problems(feedPackage(json => { delete json["molis-work"].registration; })), /molis-work-plugin-feed: has src\/registration\.ts but its package\.json does not declare it/);
  assert.match(problems(feedPackage(json => { json["molis-work"].registration = "./entry"; })), /"molis-work"\.registration must be "\.\/registration"/);
  assert.match(problems(feedPackage(json => { json.exports["./registration"] = "./dist/registration.js"; })), /exports "\.\/registration" must be \{ "types"/);
  assert.match(problems({ "plugins/native/stray/src/registration.ts": "export const registration = {};\n" }), /plugins\/native\/stray\/src\/registration\.ts belongs to no package in scripts\/workspace-packages\.mjs/);
});

test("W5-02-REG-02: --check refuses keys the contract does not have, at the top and in workbench", () => {
  assert.match(problems(feed("  summary:", "  extra: true,\n  summary:")), /has key "extra", which PluginRegistration does not declare/);
  assert.match(problems(feed("    order: 5,", "    order: 5,\n    placement: \"stage\",")), /has workbench key "placement", which PluginRegistration's workbench does not declare/);
  assert.match(problems(feed("  summary:", "  ...{},\n  summary:")), /has a member that is not a plain property \(\.\.\.\{\}\)/);
  assert.match(problems(feed("  manifest: feedManifest,", "  manifest: feedManifest,\n  manifest: feedManifest,")), /repeats key "manifest"/);
  assert.match(problems(feed("  workbench: {", "  workbench: WORKBENCH, _: {")), /must give "workbench" an object literal/);
  assert.match(problems(feed("export const registration: PluginRegistration =", "export let registration: PluginRegistration =")), /must declare `registration` with const/);
  assert.match(problems(feed("export const registration: PluginRegistration = {", "export const registration: PluginRegistration = REGISTRATION;\nconst REGISTRATION: PluginRegistration = {")), /must give `registration` an object literal/);
});

test("W5-02-REG-02: --check refuses a position or a key it cannot read, or one another plugin has", () => {
  assert.match(problems(feed("catalog_order: 10", "catalog_order: TEN")), /must give "catalog_order" a number literal/);
  const issues = BUILTIN_PLUGIN_CATALOG.find(entry => entry.project_plugin_id === "issues")!;
  assert.match(problems(feed("catalog_order: 10", `catalog_order: ${issues.catalog_order}`)), new RegExp(`catalog_order ${issues.catalog_order} is given by .+ and .+; each plugin needs its own`));
  assert.match(problems(feed("project_plugin_id: FEED_PROJECT_PLUGIN_ID", 'project_plugin_id: "Feed_Entries"')), /gives "project_plugin_id" "Feed_Entries", which is not a short id/);
  const literal = Object.fromEntries(["plugins/native/feed", "plugins/native/inbox"].map(dir => {
    const file = `${dir}/src/registration.ts`, text = readReal(file)!;
    return [file, text.replace(/project_plugin_id: [A-Z_]+,/, 'project_plugin_id: "same",')];
  }));
  assert.match(problems(literal), /project_plugin_id "same" is given by .+ and .+; each plugin needs its own/);
});

test("W5-02-REG-02: --check refuses companions and client ids that are not literal short ids", () => {
  assert.match(problems(feed('companions: ["inbox"]', "companions: [INBOX_ID]")), /must give "companions" literal short ids/);
  assert.match(problems(feed('companions: ["inbox"]', 'companions: ["Inbox"]')), /must give "companions" literal short ids/);
  assert.match(problems(feed("    order: 5,", "    order: 5,\n    clientFrom: CODING,")), /must give "clientFrom" literal short ids/);
  assert.match(problems(feed("    order: 5,", '    order: 5,\n    clientUses: "inbox",')), /must give "clientUses" literal short ids/);
});

test("W5-02-REG-02: the built catalog has no repeated key, Manifest id or position, and every id it names is in it", () => {
  assert.deepEqual(catalogProblems(BUILTIN_PLUGIN_CATALOG), []);
  const feedEntry = BUILTIN_PLUGIN_CATALOG.find(entry => entry.project_plugin_id === "feed")!;
  const coding = BUILTIN_PLUGIN_CATALOG.find(entry => entry.workbench.clientUses?.length)!;
  const lent = BUILTIN_PLUGIN_CATALOG.find(entry => entry.workbench.clientFrom !== undefined)!;
  const without = (id: string) => BUILTIN_PLUGIN_CATALOG.filter(entry => entry.project_plugin_id !== id);
  const cases: Array<[string, readonly PluginRegistration[], RegExp]> = [
    ["repeated key", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, catalog_order: 9999, manifest: { ...feedEntry.manifest, plugin_id: "io.molis.copy" } }], /two plugins have the project key feed/],
    ["repeated Manifest id", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", catalog_order: 9999 }], new RegExp(`two plugins have the Manifest id ${feedEntry.manifest.plugin_id.replaceAll(".", "\\.")}`)],
    ["repeated position", [...BUILTIN_PLUGIN_CATALOG, { ...feedEntry, project_plugin_id: "copy", manifest: { ...feedEntry.manifest, plugin_id: "io.molis.copy" } }], new RegExp(`two plugins have the catalog position ${feedEntry.catalog_order}`)],
    ["dangling companion", without("inbox"), /feed names inbox in companions, which is not in the catalog/],
    ["dangling clientFrom", without(lent.workbench.clientFrom!), new RegExp(`${lent.project_plugin_id} names ${lent.workbench.clientFrom} in workbench.clientFrom, which is not in the catalog`)],
    ["dangling clientUses", without(coding.workbench.clientUses![0]!), new RegExp(`${coding.project_plugin_id} names ${coding.workbench.clientUses![0]} in workbench.clientUses, which is not in the catalog`)],
  ];
  for (const [label, catalog, expected] of cases) assert.match(catalogProblems(catalog).join("\n"), expected, label);
});

test("W5-02-REG-03: a new plugin is its own package; the generator lists it and nothing else changes by hand", () => {
  const dir = "plugins/native/future", name = "@molis-ai/molis-work-plugin-future";
  const packages = [...WORKSPACE_PACKAGES, { path: dir, name }];
  const own = {
    [`${dir}/package.json`]: `${JSON.stringify({ name, exports: { ".": { types: "./dist/index.d.ts", import: "./dist/index.js" }, "./registration": { types: "./dist/registration.d.ts", import: "./dist/registration.js" } }, "molis-work": { registration: "./registration" } }, null, 2)}\n`,
    [`${dir}/src/registration.ts`]: readReal(FEED)!.replace(/catalog_order: \d+/, "catalog_order: 10.5").replace("project_plugin_id: FEED_PROJECT_PLUGIN_ID", 'project_plugin_id: "future"').replace(/companions: \[[^\]]*\],?\n/, ""),
  };
  assert.match(problems(own, packages), /out of date or edited by hand/, "the catalog does not list it until regenerated");
  const { text, problems: refused } = pluginRegistry(tree(own), packages);
  assert.deepEqual(refused, []);
  assert.ok(text);
  assert.match(text, /^import \{ registration as futureRegistration \} from "@molis-ai\/molis-work-plugin-future\/registration";$/m);
  const listed = text.split("\n").filter(line => line.startsWith("  ")).map(line => line.trim().replace(/,$/, ""));
  const before = BUILTIN_PLUGIN_CATALOG.filter(entry => entry.catalog_order < 10.5).length;
  assert.equal(listed.indexOf("futureRegistration"), before, "listed at its catalog_order, right after Feed");
  assert.deepEqual(problems({ ...own, [CATALOG_FILE]: text }, packages), "", "its package and the regenerated catalog are the whole change");
});
