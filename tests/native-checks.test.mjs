// specs/repository-anti-corruption §4.16 (W1-09): the checks for what is not TypeScript (scripts/gates/native-checks.mjs).
// Each check is broken once on a scratch repository and must go red; the clean case must pass. A check whose tool is not on
// this machine is skipped here and says so (CI runs rust and swift on macOS and shell on Linux, so none is skipped there);
// the shell plumbing (which files are handed over, the severity flag, a failing exit) is also tested against a stub
// shellcheck, so it is covered where the real one is missing. Plain node:test, no tsx: the macOS job installs nothing.
const script = fileURLToPath(new URL("../scripts/gates/native-checks.mjs", import.meta.url));
const scratchDirs = [];
const scratchRoot = mkdtempSync(path.join(tmpdir(), "molis-native-checks-"));
after(() => { rmSync(scratchRoot, { recursive: true, force: true }); });

const have = (command, args) => spawnSync(command, args, { stdio: "ignore" }).status === 0;
const haveRust = have("cargo", ["--version"]) && have("cargo", ["clippy", "--version"]) && have("rustfmt", ["--version"]);
const haveSwift = process.platform === "darwin" && have("swiftc", ["--version"]);
const haveShellcheck = have("shellcheck", ["--version"]);

const repoWith = (files) => {
  const dir = mkdtempSync(path.join(scratchRoot, "repo-"));
  scratchDirs.push(dir);
  execFileSync("git", ["init", "-q", "-b", "main"], { cwd: dir });
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    writeFileSync(path.join(dir, file), text);
  }
  execFileSync("git", ["add", "-A"], { cwd: dir });
  return dir;
};
const gate = (dir, args, env = {}) => {
  const run = spawnSync(process.execPath, [script, "--root", dir, ...args], { encoding: "utf8", env: { ...process.env, CARGO_TARGET_DIR: path.join(scratchRoot, "cargo-target"), CARGO_NET_OFFLINE: "true", ...env } });
  return { code: run.status, out: `${run.stdout}${run.stderr}` };
};

