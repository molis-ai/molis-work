/** The samples with their words in `text`: every string with an entry is replaced whole; ids, kinds and states have none. */
export function boardSampleText<T>(value: T, text: BoardSampleText): T {
  if (text === "zh") return value;
  const walk = (node: unknown): unknown => typeof node === "string" ? (text === "en" ? TEXT[node]?.[0] : TEXT[node]?.[1]) ?? node
    : Array.isArray(node) ? node.map(walk) : node && typeof node === "object" ? Object.fromEntries(Object.entries(node).map(([key, one]) => [key, walk(one)])) : node;
  return walk(value) as T;
}
